import pandas as pd
import matplotlib.pyplot as plt
df=pd.read_csv("cleaned_sales_data.csv")
categorySale=df.groupby("Category")["Sales"].sum()
print(categorySale)
df["Order Date"]=pd.to_datetime(df["Order Date"])
monthlySale=df.groupby(df["Order Date"].dt.to_period("M"))["Sales"].sum()
print(monthlySale)
region_profit = df.groupby("Region")["Profit"].sum()
fig,ax=plt.subplots(2,3,figsize=(13,7))
ax[0,0].bar(categorySale.index,categorySale.values,color="skyblue")
ax[0,0].set_title("Total Sales by Product Category",fontsize=16)
ax[0,0].set_xlabel("Category")
ax[0,0].set_ylabel("Sales")
ax[0,1].plot(monthlySale.index.astype(str),monthlySale.values,color="blue",marker="o",linewidth=2, markersize=5)
ax[0,1].set_title("Monthly Sales",fontsize=16)
ax[0,1].set_xlabel("month")
ax[0,1].set_ylabel("Sales")
ax[0,1].set_xticks(ticks=range(0,len(monthlySale),3),labels=monthlySale.index.astype(str)[::3],rotation=45,ha="right")
ax[0,2].hist(df["Sales"],bins=20,color="grey",edgecolor="black")
ax[0,2].set_title("Sales Distribution",fontsize=16)
ax[0,2].set_xlabel("Sales Amount")
ax[0,2].set_ylabel("Number of orders")
ax[1,0].scatter(df["Sales"],df["Profit"], color="teal",alpha=0.5)
ax[1,0].set_title("Sales vs Profit",fontsize=16)
ax[1,0].set_xlabel("Sales")
ax[1,0].set_ylabel("Profit")
ax[1,0].axhline(y=0,color="red")
ax[1,1].boxplot(df["Profit"],patch_artist=True,boxprops=dict(facecolor="lightblue"),medianprops=dict(color="red"))
ax[1,1].set_title("Profit Distribution", fontsize=16)
ax[1,1].set_ylabel("Profit")
ax[1,2].barh(region_profit.index,region_profit.values,color="teal")
ax[1, 2].set_title("Profit by Region", fontsize=16)
ax[1, 2].set_xlabel("Total Profit")
ax[1, 2].set_ylabel("Region")
plt.tight_layout()
plt.savefig("Chart/retail_sales_dashboard.png",dpi=300)
plt.show()
